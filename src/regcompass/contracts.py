    run_id: str
    kind: Literal["run", "discovery"]
    economy: str
    pillars: list[int] = Field(default_factory=list)
    indicators: list[str] | None = None
    engine: str | None = None
    # interrupted: the process that opened this record died before closing it,
    # and the server's next start said so rather than leaving it reading
