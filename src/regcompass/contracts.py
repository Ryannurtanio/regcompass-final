# Closed vocabularies
# ---------------------------------------------------------------------------

# Economy codes are ISO 3166-1 alpha-2, uppercase. The SET of Economies is DATA
# (config/portals.yaml), not a Literal: adding an Economy must never be a
# contract edit. The shape is checked here; MEMBERSHIP of the configured
# registry is checked at the boundaries that know which registry is loaded
# (the CLI's choices, the server's request validation, the export's portal
# lookup), so a test fixture can carry a code this checkout does not ship.
ECONOMY_CODE_PATTERN = r"^[A-Z]{2}$"
EconomyCode = Annotated[str, Field(pattern=ECONOMY_CODE_PATTERN)]

# Canonical NUMERIC indicator IDs; ALL internal logic uses these. The ID is
# always TEXT: three of them are three-level (12.4.1) and two carry a leading
# zero (4.01, 12.01), so a float would destroy them. The SET of Indicators is
# data too (config/indicators.json, generated by scripts/make_indicators.py
# from the organizer's own sheets); only the shape lives here. Emission format
# (numeric default, P-code alternative) is driven solely by
# indicator_id_crosswalk config.
INDICATOR_ID_PATTERN = r"^\d{1,2}(\.\d{1,2}){1,2}$"
IndicatorId = Annotated[str, Field(pattern=INDICATOR_ID_PATTERN)]

# Exactly NEW or KNOWN, case-sensitive, PROVISION-level.
DiscoveryTag = Literal["NEW", "KNOWN"]

# passed only after BOTH the byte-for-byte substring check and the subsection
# regex check pass; dropped after retries exhaust.
VerificationStatus = Literal["unverified", "passed", "dropped"]

# uncertainty_flags vocabulary, verbatim.
UncertaintyFlag = Literal[
    "missing-information",
    "contradictory-sources",
    "possible-amendment-or-repeal",
    "no-clear-translation-equivalent",
]

# M8 relationship vocabulary.
RelationshipToGroup = Literal[
    "sole_source", "complementary", "superseded_by", "supersedes", "conflicting"
]

# Where the novelty sits for a NEW tag; novelty is assessed at provision level.
NoveltyScope = Literal["law", "provision"]

# M4 chunk accounting: every char of the stream is a section or explicitly
# labelled non-section material.
ChunkKind = Literal["section", "front_matter", "toc", "schedule", "other"]

ReviewStatus = Literal["accepted", "rejected", "flagged", "corrected"]


