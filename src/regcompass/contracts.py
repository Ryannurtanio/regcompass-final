# A demonstration Corpus, and every row built on it says so.
FIXTURE_SOURCE_KIND = "fixture"


# --- how a manual upload is filed in the fetch manifest --------------------
#
# The manifest's primary key is the URL, which is right for Discovery: a URL
# fetched once is never fetched again, and that is what makes a second Engine's
# pass over the same Corpus cost nothing. It is wrong for an upload. Several
# statutes are published under one landing page, and an assessor pasting that
# page for each of them was filing every upload on ONE manifest row: the second
# file overwrote the first row's bytes while the first Document kept its name,
# so one law's text appeared under another law's title.
#
# So an upload is keyed by its address AND its own digest. The address says
# where the Document is published (and is what reaches the Corpus row's Source
# URL column); the digest says WHICH Document, which is the part the address
# alone could never carry. An upload with no address keeps the older scheme,
# where the digest is the whole key.
#
# These live here, beside the source kinds, because the ingest reads a manifest
# key back into a Source URL and must not import the add lane to learn how.

#: The key an upload with no Source URL is filed under. It never reaches the
#: Corpus row's Source URL column, and never reaches an export.
LOCAL_UPLOAD_SCHEME = "local-upload"

#: What separates an upload's address from its digest inside a manifest key.
UPLOAD_DIGEST_MARKER = "#sha256="

_SHA256_HEX = re.compile(r"\A[0-9a-f]{64}\Z")


def manifest_key_for_upload(source_url: str | None, sha256: str) -> str:
    """The manifest key one uploaded file is filed under.

    With an address: that address plus the digest, so two files an operator
    gave the same address both keep a row of their own. Without one: the digest
    under a scheme nothing will mistake for a Portal address."""
    if not source_url:
        return f"{LOCAL_UPLOAD_SCHEME}:{sha256}"
    return f"{source_url}{UPLOAD_DIGEST_MARKER}{sha256}"


def manifest_address(key: str) -> str | None:
    """Where the Document behind this manifest key is published, or None.

    A Discovery key is already the address. An upload key carries the digest
    beside it and gives back the address alone; an address-less upload gives
    back None, which is the truth about it and what makes the local-copy link
    and the Export's refusal both read correctly."""
    if key.startswith(f"{LOCAL_UPLOAD_SCHEME}:"):
        return None
    address, marker, digest = key.rpartition(UPLOAD_DIGEST_MARKER)
    if marker and address and _SHA256_HEX.match(digest):
        return address
    return key
