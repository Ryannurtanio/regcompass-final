class Chunk(_Contract):
    """A section-level slice of the canonical stream.

    text MUST equal full_text[char_start:char_end]; construct via from_stream()
    so the slice identity holds by construction. M4's exit test re-proves it.
    """

    chunk_id: str
    document_id: str
    char_start: int = Field(ge=0)
    char_end: int = Field(ge=0)
    text: str
    section_label: str  # e.g. 's. 16', 'Part IVA s. 26(2)', 'front matter'
    chunk_kind: ChunkKind = "section"
    page_start: int | None = Field(default=None, ge=1)
    page_end: int | None = Field(default=None, ge=1)

    @model_validator(mode="after")
    def _slice_consistent(self) -> "Chunk":
        if self.char_end < self.char_start:
            raise ValueError("char_end < char_start")
        if len(self.text) != self.char_end - self.char_start:
            raise ValueError(
                f"text length {len(self.text)} != span {self.char_end - self.char_start}: "
                "chunk text must be a slice of the canonical stream, never re-emitted"
            )
        return self

    @classmethod
    def from_stream(
        cls,
        canonical: CanonicalText,
        chunk_id: str,
        char_start: int,
        char_end: int,
        section_label: str,
        chunk_kind: ChunkKind = "section",
        page_start: int | None = None,
        page_end: int | None = None,
    ) -> "Chunk":
        return cls(
            chunk_id=chunk_id,
            document_id=canonical.document_id,
            char_start=char_start,
            char_end=char_end,
            text=canonical.slice(char_start, char_end),
            section_label=section_label,
            chunk_kind=chunk_kind,
            page_start=page_start,
            page_end=page_end,
        )


