"""Pydantic I/O contracts for every module seam in the pipeline.

These models ARE the module boundaries. Field names for the working JSON record are
fixed by the record schema. Changing a model here means the corresponding module
specs must be updated to match.

Invariant philosophy: cheap structural checks (bounds, ordering, enum membership,
exactly-one-authoritative) live here as validators and fail at construction time.
Deep invariants that need the canonical stream (slice identity, substring
verification) live in the owning module and its tests - a contract model never
holds enough context to prove them alone.
"""

from __future__ import annotations

import re
import unicodedata
from datetime import date, datetime
from typing import Annotated, Literal

from pydantic import BaseModel, ConfigDict, Field, model_validator

