class UnknownEngine(ValueError):
    """The caller named an Engine that config/models.yaml does not declare. The
    message always lists the declared names, so a typo is self-correcting."""


ENGINE_NAME_RE = r"^[a-z0-9][a-z0-9-]*$"


# The ceiling on Mapping calls in flight, for the registry, the pipeline, the
# command line and the run endpoint alike. One number, declared where the
# Engine model itself can bound against it, so the three callers cannot drift.
MAX_CONCURRENCY = 32


class Engine(_Contract):
    """One declared Engine: the whole model configuration a run uses, named in
    the UI, on the command line and in the Run Record. Every field is required
    (no defaults) except num_retries, so a half-written registry entry fails at
    load instead of silently inheriting a value nobody chose. num_retries is
    pinned 0 in config and asserted here: silent transport retries corrupt our
    attempt counting (a known LiteLLM/OpenAI SDK trap).

    concurrency is how many Mapping calls one Run may have in flight on THIS
    Engine. It belongs to the Engine rather than to the pipeline because the
    limit is the provider's: a hosted Engine tolerates several at once, a
    locally served one is a single machine and stays at 1, and the fake Engine
    has nothing to gain from a thread pool. It is declared, never defaulted, so
    a new registry entry cannot inherit a rate limit nobody chose for it."""

    name: str  # the registry key, injected by ModelsConfig
    display_name: str
    litellm_model: str  # e.g. "openrouter/qwen/qwen3-30b-a3b-instruct-2507"
    provider: Literal["openrouter", "ollama", "fake"]
    api_key_env: str | None  # env var NAME only; the key itself never leaves .env
    usd_per_million_input_tokens: float = Field(ge=0)
    usd_per_million_output_tokens: float = Field(ge=0)
    open_weights: bool
    structured_output: Literal["json_schema", "ollama_format", "none"]
    concurrency: int = Field(ge=1, le=MAX_CONCURRENCY)
    num_retries: Literal[0] = 0


