class ReconciledGroup(_Contract):
    """M8 output for one (economy, indicator) group: exactly one authoritative
    mapping (the controlling evidence); losers stay recorded, never dropped."""

    group_id: str
    economy: EconomyCode
    indicator_id: IndicatorId
    mapping_ids: list[str] = Field(min_length=1)
    authoritative_mapping_id: str
    relationships: dict[str, RelationshipToGroup] = Field(default_factory=dict)
    reconciliation_notes: str | None = None

    @model_validator(mode="after")
    def _exactly_one_authoritative(self) -> "ReconciledGroup":
        if self.authoritative_mapping_id not in self.mapping_ids:
            raise ValueError("authoritative_mapping_id must be a member of mapping_ids")
        if len(set(self.mapping_ids)) != len(self.mapping_ids):
            raise ValueError("duplicate mapping_ids in group")
        unknown = set(self.relationships) - set(self.mapping_ids)
        if unknown:
            raise ValueError(f"relationships reference unknown mapping_ids: {sorted(unknown)}")
        return self


