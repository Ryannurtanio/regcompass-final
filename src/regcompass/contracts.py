class OcrQuality(_Contract):
    """Per-document OCR quality proxies (M2). CER gate is < 0.05.

    ocr_quality_cer holds a MEASURED character error rate when a hand-checked
    reference exists (test/eval runs); cer_proxy_flag is the production stand-in
    (confidence + dictionary proxies below threshold = suspected CER >= 5%)."""

    mean_word_confidence: float = Field(ge=0.0, le=1.0)
    # None when the proxy does not apply: it counts hits against an ENGLISH
    # legal wordlist, so on a Lao or Thai stream it would read 0.0 and be taken
    # for catastrophic OCR. dictionary_hit_rate_note carries the reason.
    dictionary_hit_rate: float | None = Field(default=None, ge=0.0, le=1.0)
    dictionary_hit_rate_note: str | None = None
    # Why manual_review was forced regardless of the measured proxies (a
    # Language with no vendored traineddata was read as English).
    manual_review_reason: str | None = None
    ocr_quality_cer: float | None = Field(default=None, ge=0.0, le=1.0)
    cer_proxy_flag: bool = False
    escalated_to_rapidocr: bool = False
    manual_review: bool = False


class CanonicalText(_Contract):
    """THE canonical stream for one document, produced exactly once (M1 or M2).

    Everything downstream slices full_text by character offsets; nothing may
    re-flow, re-wrap, or clean it up. The verbatim substring check (M7) runs
    against this same stream.
    """

    document_id: str
    source_sha256: str = Field(pattern=r"^[0-9a-f]{64}$")
    extractor: str  # e.g. "pdfplumber"
    extractor_version: str  # pinned; part of the ground-truth definition
    full_text: str
    pages: list[PageSpan] = Field(default_factory=list)
    words: list[WordBox] = Field(default_factory=list)
    language: str | None = None  # ISO 639-1 where known; None = undetermined
    low_yield_pages: list[int] = Field(default_factory=list)  # < 50 chars -> OCR flag
    ocr_applied: bool = False
    ocr_quality: OcrQuality | None = None

    @model_validator(mode="after")
    def _composed(self) -> "CanonicalText":
        """The stream in one Unicode form (NFC), made here so that every
        producer (text layer, HTML, OCR, a stored stream read back) yields it.
        Already-composed text, which is nearly all of it, passes untouched."""
        from .textnorm import ComposedText, is_nfc

        if is_nfc(self.full_text) and all(is_nfc(w.text) for w in self.words):
            return self
        composed = ComposedText(self.full_text)
        self.full_text = composed.text
        self.pages = [
            p.model_copy(update={
                "char_start": composed.start(p.char_start),
                "char_end": composed.end(p.char_end),
            })
            for p in self.pages
        ]
        self.words = [
            w.model_copy(update={
                "text": unicodedata.normalize("NFC", w.text),
                "char_start": composed.start(w.char_start),
                "char_end": composed.end(w.char_end),
            })
            for w in self.words
        ]
        return self

    @model_validator(mode="after")
    def _spans_in_bounds(self) -> "CanonicalText":
        n = len(self.full_text)
        for p in self.pages:
            if p.char_end > n:
                raise ValueError(f"page {p.page_number} char_end {p.char_end} > stream length {n}")
        for w in self.words:
            if w.char_end > n:
                raise ValueError(f"word at {w.char_start} char_end {w.char_end} > stream length {n}")
        return self

    def slice(self, char_start: int, char_end: int) -> str:
        """The ONLY sanctioned way to obtain text from the stream."""
        return self.full_text[char_start:char_end]


