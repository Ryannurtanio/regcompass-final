class CrawlManifestEntry(_Contract):
    """One URL's row in the crawl manifest (M10), the checkpoint/resume source
    of truth. The stored bytes are the exact server response body; sha256 is
    computed over those bytes and doubles as the dedupe key. A URL whose bytes
    already exist on disk is still status='fetched' with is_duplicate_of set
    and local_path pointing at the single stored copy."""

    url: str
    economy: EconomyCode
    kind: Literal["document", "index"] = "document"
    source_family: str | None = None
    filename_hint: str | None = None
    status: Literal["pending", "fetched", "failed"] = "pending"
    http_status: int | None = None
    method: str | None = None  # httpx | curl_cffi | playwright
    sha256: str | None = Field(default=None, pattern=r"^[0-9a-f]{64}$")
    content_type: str | None = None
    size_bytes: int | None = Field(default=None, ge=0)
    local_path: str | None = None
    is_duplicate_of: str | None = None
    attempts: int = Field(default=0, ge=0)
    error: str | None = None
    fetched_at: datetime | None = None

    @model_validator(mode="after")
    def _fetched_has_bytes(self) -> "CrawlManifestEntry":
        if self.status == "fetched" and (self.sha256 is None or self.local_path is None):
            raise ValueError("a fetched entry must carry sha256 and local_path")
        if self.status == "fetched" and self.fetched_at is None:
            raise ValueError("a fetched entry must carry fetched_at")
        return self


