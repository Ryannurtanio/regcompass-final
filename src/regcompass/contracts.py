# The organizer's Language dropdown, verbatim (OUTPUT_TEMPLATE_FINAL_ROUND.xlsx,
# Output Data sheet, data validation on N9:N109). Every Document's Language of
# Source must be one of these; anything else, Malay and Portuguese included, is
# "Other".
ORGANIZER_LANGUAGES: tuple[str, ...] = (
    "English",
    "Thai",
    "Vietnamese",
    "Bahasa Indonesia",
    "Chinese",
    "Hindi",
    "Kazakh",
    "Russian",
    "Lao",
    "Mongolian",
    "Other",
)

# Spellings a Document's recorded Language may carry that are not the
# organizer's own word for it. Everything absent from this table AND from
# ORGANIZER_LANGUAGES is "Other": Malay, Portuguese, Tetum and Khmer have no
# organizer value, so naming them would be inventing a dropdown entry.
LANGUAGE_ALIASES: dict[str, str] = {
    "indonesian": "Bahasa Indonesia",
    "bahasa": "Bahasa Indonesia",
    "bahasa indonesian": "Bahasa Indonesia",
    "mandarin": "Chinese",
    "chinese (simplified)": "Chinese",
    "simplified chinese": "Chinese",
    "viet": "Vietnamese",
    "tiếng việt": "Vietnamese",
    "laotian": "Lao",
    "kazakhstani": "Kazakh",
    "mongol": "Mongolian",
    "english (translation)": "English",
}


def organizer_language(raw: str | None) -> str:
    """The Language of Source value the organizer's workbook accepts, for a
    Document whose recorded Language is `raw`.

    The dropdown on Output Data N9:N109 has eleven values and is advisory only,
    so nothing but this function stops an out-of-list word reaching the file
    the secretariat scores criterion C1c from. A Language we cannot place -
    Malay, Portuguese, Tetum, or none recorded at all - is "Other", never a
    guess at the nearest entry."""
    if not raw:
        return "Other"
    cleaned = raw.strip()
    for value in ORGANIZER_LANGUAGES:
        if cleaned.casefold() == value.casefold():
            return value
    return LANGUAGE_ALIASES.get(cleaned.casefold(), "Other")


# The Discovery strategy that fetches nothing. An Economy on this strategy is
# reviewed from Documents added by hand, so it is the one case where the host
# whitelist may be empty.
MANUAL_STRATEGY = "manual"

# Every Discovery strategy name a Portal may name. The VOCABULARY lives here,
# on the base tier, because PortalConfig must validate it and config loading
# must work without the live extra installed; crawl.STRATEGIES binds each name
# to the function that implements it and a test asserts the two agree. Adding
# an Economy that reuses an existing strategy is a portals.yaml edit alone;
# adding a strategy is one entry here and one in crawl.STRATEGIES.
STRATEGY_NAMES: tuple[str, ...] = (
    "playwright",
    "curl_cffi_ladder",
    "httpx",
    "dspace_rest",
    MANUAL_STRATEGY,
)


# What a Portal's configuration may say an UNAVAILABLE robots.txt (a 5xx)
# means for that Portal. `refuse` is RFC 9309's own reading and the default
# everywhere: the rules may exist and the Portal cannot show them, so nothing
# is requested. `proceed` is an operator's explicit decision, recorded per
# Portal with its reason, that this Portal's silence is read as publishing no
# rules; every other politeness rule (the spacing floor, the host whitelist,
# the identified agent, the published rules whenever the Portal CAN serve
# them) is untouched, and every record says which policy let the request out.
ROBOTS_UNAVAILABLE_POLICIES: tuple[str, ...] = ("refuse", "proceed")

# How many connections a Discovery opens to one Portal at a time. The crawler
# caps its single pooled client at this (crawl.one_connection), and the Settings
# screen reads the same name, so the screen cannot disagree with the behaviour.
CONNECTIONS_PER_HOST = 1

# RFC 9309 section 2.3.1.4: a robots.txt that has stayed unavailable (5xx) for
# this many days, counted from the Portal's recorded robots_unreachable_since
# date, may be treated as publishing no rules (crawl.ROBOTS_UNREACHABLE_GRACE).
ROBOTS_UNREACHABLE_GRACE_DAYS = 30


class PortalConfig(_Contract):
    """One Economy's official Portal: host whitelist, Discovery strategy, the
    Coverage Matrix spelling the export writes, and the Languages to expect."""

    economy: EconomyCode
    # The organizer Coverage Matrix spelling ("Lao PDR", "Viet Nam", "Russian
    # Federation"); this is the value written into the Economy column.
    official_name: str = Field(min_length=1)
    # The UN member-state name, only where it differs from official_name.
    un_name: str | None = None
    # Organizer Language values; the first is this Economy's default.
    languages: list[str] = Field(min_length=1)
    hosts: list[str] = Field(default_factory=list)  # whitelist; Source URL host must be in here
    strategy: str = Field(min_length=1)  # one of STRATEGY_NAMES
    # PERMANENTLY manual: this Portal's own site rules forbid automated
    # collection, so Discovery must never be pointed at it and every Document
    # arrives through "Add document". This is NOT the same statement as
    # `strategy: manual`, which nine Economies carry today only because no
    # Discovery strategy has been wired for them yet and which they will lose.
    manual_only: bool = False
    prepared: bool = False  # the Corpus has actually been fetched and checked
    live_test_pool: bool = False  # one of the nine Economies the organizers may draw
    # The politeness FLOOR for this Portal: the least time Discovery may leave
    # between two requests to the same host. A published robots.txt crawl-delay
    # RAISES it and never lowers it, so this is a promise, not a target.
    min_interval_seconds: float = Field(default=1.0, gt=0)
    # The first date we saw this Portal answer its robots.txt with a server
    # error (5xx), recorded by hand after checking the Portal. RFC 9309 section
    # 2.3.1.4 asks a crawler to assume complete disallow while robots.txt is
    # unavailable, and allows it to treat a Portal that has stayed that way for
    # a reasonable period (the RFC names 30 days) as publishing no rules. This
    # date is what turns that second half from a judgement call into data: with
    # no date recorded, an unreadable robots.txt simply refuses.
    robots_unreachable_since: date | None = None
    # What an unavailable robots.txt means for THIS Portal: 'refuse' (the
    # default, and the rule everywhere it is absent) or 'proceed', an
    # operator's recorded decision that this Portal's 5xx is read as no rules
    # published. It bounds nothing else: the spacing floor, the host
    # whitelist and the published rules all apply exactly as before, and the
    # record of any request made under 'proceed' carries the status the Portal
    # gave and this policy, so nobody has to infer why we went ahead.
    robots_unavailable_policy: str = "refuse"
    # Hosts of this Portal that answer only over plain http from where we
    # run (port 443 closed on the path). A Source URL on one of them may be
    # http://, and its robots.txt is then read over http too; every other
    # host keeps reading robots.txt over https. It is a per-host allowance,
    # never a downgrade for the Economy.
    http_hosts: list[str] = Field(default_factory=list)
    # How long one request of a Discovery by Pillar may take on this
    # Portal's hosts, for a Portal whose answers are slow but whole. Left
    # out, the Discovery's own short timeout applies.
    fetch_timeout_seconds: float | None = Field(default=None, gt=0)
    notes: str | None = None

    @model_validator(mode="after")
    def _whitelist_or_manual(self) -> "PortalConfig":
        if self.strategy not in STRATEGY_NAMES:
            raise ValueError(
                f"{self.economy}: unknown Discovery strategy '{self.strategy}';"
                f" known strategies are {list(STRATEGY_NAMES)}"
            )
        unknown = [lang for lang in self.languages if lang not in ORGANIZER_LANGUAGES]
        if unknown:
            raise ValueError(
                f"{self.economy}: languages not on the organizer's list: {unknown}"
                f" (use 'Other'; the list is {list(ORGANIZER_LANGUAGES)})"
            )
        if not self.hosts and self.strategy != MANUAL_STRATEGY:
            raise ValueError(
                f"{self.economy}: an empty host whitelist is only allowed with"
                f" strategy '{MANUAL_STRATEGY}', not '{self.strategy}'"
            )
        if self.robots_unavailable_policy not in ROBOTS_UNAVAILABLE_POLICIES:
            raise ValueError(
                f"{self.economy}: robots_unavailable_policy"
                f" '{self.robots_unavailable_policy}' is not a policy;"
                f" it is one of {list(ROBOTS_UNAVAILABLE_POLICIES)}, and"
                " leaving the line out means 'refuse'"
            )
        if self.manual_only and self.strategy != MANUAL_STRATEGY:
            raise ValueError(
                f"{self.economy}: manual_only means Discovery must never run"
                f" here, so its strategy must be '{MANUAL_STRATEGY}',"
                f" not '{self.strategy}'"
            )
        stray = [h for h in self.http_hosts if h not in self.hosts]
        if stray:
            raise ValueError(
                f"{self.economy}: http_hosts must be hosts of this Portal;"
                f" {stray} are not in its hosts list"
            )
        return self


# Hosts no lane of ours ever requests, on any path and any rung, whatever a
# baseline row, a Portal answer, an operator or a redirect names: the Thai law
# portal and the Royal Gazette (out of scope by decision), and China's national
# law database, whose robots.txt forbids every crawler. Here, not in crawl.py,
# so the add lane can refuse them without importing the network stack.
NEVER_REQUESTED_HOSTS = frozenset(
    {"law.go.th", "ratchakitcha.soc.go.th", "flk.npc.gov.cn"}
)


def is_never_requested(host: str) -> bool:
    """Is this host, or a domain it sits under, on the never-requested list?
    Any subdomain counts, and a trailing dot or a port changes nothing."""
    h = (host or "").split("@")[-1].split(":")[0].rstrip(".").lower()
    return any(h == d or h.endswith("." + d) for d in NEVER_REQUESTED_HOSTS)


